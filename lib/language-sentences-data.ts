/**
 * Picks a round of `roundSize` unseen sentences from `pool`. Callers must
 * only invoke this once per game session (e.g. inside a `useState(() => ...)`
 * lazy initializer) — TopicHub re-invokes a mode's render() on every
 * re-render while that mode is active, so calling this directly in render
 * would re-randomize (and reset progress on) an in-progress round.
 */
export function pickSentenceRound(lang: LanguageCode, pool: string[], roundSize = 5): string[] {
  const unique = [...new Set(pool)]
  const picked: string[] = []
  let remaining = [...unique]
  const pickCount = Math.min(roundSize, unique.length)
  for (let i = 0; i < pickCount; i++) {
    const sentence = pickUnseen(`language-sentences:${lang}`, remaining, (s) => s)
    picked.push(sentence)
    remaining = remaining.filter((s) => s !== sentence)
  }
  return picked
}
